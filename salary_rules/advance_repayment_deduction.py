# قاعدة راتب (Salary Rule): حجز السلفة الخارجية من الراتب بعد فوات تاريخ الاستحقاق
#
# الفكرة:
#   - الموظف يستلم السلفة ويتعهد يرجعها كاملة نقداً بتاريخ معيّن (مثلاً بعد 3 أشهر)،
#     وما ينقطع من راتبه شي قبل هذا التاريخ.
#   - تُسجَّل كاستقطاع راتب (hr.salary.attachment) من نوع "سلفة خارجية" (تتسدد من خارج الراتب)،
#     وتاريخ البدء = تاريخ الاستحقاق، فأودو ما يضيفها لأي قسيمة قبل هذا التاريخ.
#   - إذا جاب الفلوس قبل الموعد: إجراء الخادم salary_attachment_cash_repayment يغلقها.
#   - إذا ما جابها: أودو يضيف للقسيمة إدخالاً بمبلغ المتبقي، وهذه القاعدة تحجز المتبقي
#     من صافي الراتب وبحد أقصى الصافي كله، والباقي ينتقل للشهر الجاي تلقائياً.
#     المبلغ المحجوز فعلاً يظهر بالقسيمة ويُسجَّل كتسديد على السلفة عند تأكيد القسيمة.
#
# السلفة تنصرف وترجع بنفس عملتها (دينار من وإلى صندوق الدينار، دولار من وإلى صندوق الدولار)،
# فلكل عملة نوع استقطاع وقاعدة بكود خاص، والحجز دائماً من راتب بنفس العملة وبدون تحويل:
#   سلفة خارجية - دينار   الكود EXTADV_IQD   صندوق الدينار   تُضاف لهياكل الرواتب المحسوبة بالدينار
#   سلفة خارجية - دولار   الكود EXTADV_USD   صندوق الدولار   تُضاف لهياكل الرواتب المحسوبة بالدولار
#
# إعدادات كل قاعدة (Payroll > Configuration > Rules):
#   الاسم: حجز سلفة خارجية - دينار/دولار
#   الكود: EXTADV_IQD أو EXTADV_USD (نفس كود نوع الاستقطاع ونوع الإدخال حرفياً)
#   الفئة: Deduction (DED)        التسلسل: بعد كل قواعد الاستقطاع وقبل NET (مثلاً 195)
#   الشرط: Python Expression  ←  result = 'EXTADV_IQD' in inputs   (أو 'EXTADV_USD')
#   المبلغ: Python Code       ←  الكود أدناه، مع تغيير CODE بقاعدة الدولار
#
# مكتوب لـ Odoo 17 فما فوق (categories و inputs قواميس تُقرأ بالأقواس).

CODE = 'EXTADV_IQD'  # بقاعدة الدولار: 'EXTADV_USD'

# صافي الراتب المتاح لحد هذه القاعدة: نفس معادلة NET، وفئة DED تتجمع حسب التسلسل
# فتشمل السلف الدائمية والمؤقتة وكل استقطاع قبلها. إذا معادلة NET عندكم مختلفة انسخوها هنا.
available = categories['BASIC'] + categories['ALW'] + categories['DED']

# المتبقي من السلفة: أودو يحط بالإدخال أقل قيمة بين "المبلغ الشهري" والمتبقي،
# لذلك المبلغ الشهري للسلفة يكون مساوياً للمبلغ الكلي
due = inputs[CODE].amount

result = -min(due, max(available, 0))
